#!/usr/bin/env python3
"""Turn photos into small dot-matrix colour grids for the site (dev-only feature).

    python3 tools/dotpic.py          # rebuilds js/photos.js from the list below

Only the tiny grids go into the repo, never the source photos. Needs Pillow (pip install pillow).
Each entry: key -> (source image, crop box (l, t, r, b) or None, columns, drop_background)
"""
import base64, json, os, sys
from PIL import Image, ImageEnhance, ImageOps

SRC = os.environ.get("DOTPIC_SRC", "photos-src")   # keep originals outside the repo, or in a git-ignored folder
PHOTOS = {
    "me":       ("me.png",       (28, 10, 222, 214), 44, True),
    "inkiniki": ("inkiniki.jpg", (150, 830, 1400, 1490), 100, False),
}

def grid(path, crop, cols, drop_bg):
    im = Image.open(path).convert("RGB")
    if crop: im = im.crop(crop)
    im = ImageOps.autocontrast(im, cutoff=1)
    im = ImageEnhance.Contrast(ImageEnhance.Color(im).enhance(1.25)).enhance(1.12)
    rows = max(1, round(cols * im.height / im.width))
    sm = im.resize((cols, rows), Image.LANCZOS)
    px = [[sm.getpixel((x, y)) for x in range(cols)] for y in range(rows)]
    bg = set()
    if drop_bg:   # flood-fill the light, grey background in from the edges
        light = lambda c: min(c) > 175 and max(c) - min(c) < 40
        todo = [(x, y) for x in range(cols) for y in (0, rows - 1)] + [(x, y) for y in range(rows) for x in (0, cols - 1)]
        while todo:
            x, y = todo.pop()
            if (x, y) in bg or not (0 <= x < cols and 0 <= y < rows) or not light(px[y][x]): continue
            bg.add((x, y)); todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    out = bytearray()
    for y in range(rows):
        for x in range(cols):
            r, g, b = (0, 0, 0) if (x, y) in bg else px[y][x]   # 0,0,0 = empty dot
            if (x, y) not in bg and r == g == b == 0: r = g = b = 1
            out += bytes((r, g, b))
    return {"w": cols, "h": rows, "px": base64.b64encode(bytes(out)).decode()}

def main():
    data = {k: grid(os.path.join(SRC, f), c, n, d) for k, (f, c, n, d) in PHOTOS.items()
            if os.path.exists(os.path.join(SRC, f)) or sys.exit(f"missing {SRC}/{f}")}
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "js", "photos.js"), "w") as fh:
        fh.write("/* GENERATED by tools/dotpic.py: dot-matrix photo grids (RGB, 0,0,0 = empty). Loaded only in dev mode. */\n")
        fh.write("window.NK = window.NK || {};\nNK.photos = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote js/photos.js", {k: (v["w"], v["h"]) for k, v in data.items()})

if __name__ == "__main__":
    main()
